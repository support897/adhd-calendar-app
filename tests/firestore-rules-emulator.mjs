import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { doc, getDoc, setDoc, deleteDoc, serverTimestamp, Timestamp } from "firebase/firestore";
import fs from "fs";
let pass = 0, fail = 0; const t = async (n, p) => { try { await p; pass++; console.log("PASS " + n); } catch (e) { fail++; console.log("FAIL " + n + " :: " + String(e.message).slice(0, 120)); } };
const env = await initializeTestEnvironment({ projectId: "pace-rules", firestore: { rules: fs.readFileSync("app/firestore.rules", "utf8"), host: "127.0.0.1", port: 8085 } });
const A = env.authenticatedContext("userA", { firebase: { sign_in_provider: "password" } }).firestore();
const B = env.authenticatedContext("userB", { firebase: { sign_in_provider: "password" } }).firestore();
const anon = env.authenticatedContext("guest1", { firebase: { sign_in_provider: "anonymous" } }).firestore();
const out = env.unauthenticatedContext().firestore();
const st = (uid) => "users/" + uid + "/data/state";
const good = { stateJson: "{}", updatedAt: new Date().toISOString() };
await t("A can save own state", assertSucceeds(setDoc(doc(A, st("userA")), good)));
await t("A can read own state", assertSucceeds(getDoc(doc(A, st("userA")))));
await t("B cannot read A's state", assertFails(getDoc(doc(B, st("userA")))));
await t("B cannot write A's state", assertFails(setDoc(doc(B, st("userA")), good)));
await t("B cannot delete A's state", assertFails(deleteDoc(doc(B, st("userA")))));
await t("signed-out cannot read", assertFails(getDoc(doc(out, st("userA")))));
await t("signed-out cannot write", assertFails(setDoc(doc(out, st("userA")), good)));
await t("guest (anonymous) cannot write cloud data", assertFails(setDoc(doc(anon, st("guest1")), good)));
await t("A cannot add extra fields to state", assertFails(setDoc(doc(A, st("userA")), { ...good, evil: 1 })));
await t("A can create own spine with a fresh createdAt", assertSucceeds(setDoc(doc(A, "users/userA"), { createdAt: Timestamp.now() })));
await t("A cannot backdate createdAt", assertFails(setDoc(doc(B, "users/userB"), { createdAt: Timestamp.fromMillis(Date.now() - 86400e3 * 30) })));
await t("B cannot read A's spine", assertFails(getDoc(doc(B, "users/userA"))));
await t("A cannot grant themselves a subscription", assertFails(setDoc(doc(A, "subscriptions/userA"), { plus: true })));
await t("nobody reads the owner config", assertFails(getDoc(doc(A, "_owner/config"))));
await t("A can erase own state (right to delete)", assertSucceeds(deleteDoc(doc(A, st("userA")))));
await env.cleanup();
console.log("\n" + pass + " passed, " + fail + " failed"); process.exit(fail ? 1 : 0);
